/** Gaussian blob in lat/lon space. */
type Blob = [lat: number, lon: number, rLat: number, rLon: number, amp: number];
function blob(lat: number, lon: number, [cl, co, rl, ro, amp]: Blob): number {
  let dLon = Math.abs(lon - co);
  if (dLon > 180) dLon = 360 - dLon;
  return amp * Math.exp(-(((lat - cl) / rl) ** 2) - (dLon / ro) ** 2);
}
const maxBlob = (lat: number, lon: number, blobs: Blob[]) => blobs.reduce((m, b) => Math.max(m, blob(lat, lon, b)), 0);

