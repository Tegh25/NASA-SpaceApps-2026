// ---------- heightmaps ----------
function heightmap(id: string): object {
  const W = 128;
  const H = 128;
  const r = mulberry32(id.length * 977 + id.charCodeAt(5));
  const craters: [number, number, number, number][] = [];
  for (let i = 0; i < 40; i++) craters.push([r() * W, r() * H, 1.5 + r() ** 3 * 10, 0.4 + r() * 0.6]);
  const field = new Float32Array(W * H);
  const crater = (d: number, R: number, depth: number) => {
    const x = d / R;
    if (x < 1) return depth * (x * x - 1) + depth * 0.15;
    return depth * 0.15 * Math.exp(-((x - 1) * 4));
  };
  let mpp = 100;
  for (let y = 0; y < H; y++)
    for (let x = 0; x < W; x++) {
      let h = (valueNoise(x / 16, y / 16, id.length) - 0.5) * 120 + (valueNoise(x / 5, y / 5, 3) - 0.5) * 30;
      const cx = x - W / 2;
      const cy = y - H / 2;
      const d = Math.hypot(cx, cy);
      switch (id) {
        case 'moon-shackleton-rim':
          mpp = 250;
          h += crater(Math.hypot(cx + 30, cy), 42, 4000);
          break;
        case 'moon-malapert-massif':
          mpp = 300;
          h += 4500 * Math.exp(-((d / 30) ** 2)) + 500 * Math.exp(-(((cx - 20) / 15) ** 2) - ((cy + 10) / 25) ** 2);
          break;
        case 'moon-mare-tranquillitatis':
          mpp = 60;
          h *= 0.3;
          break;
        case 'mars-jezero': {
          mpp = 400;
          h += crater(d, 50, 600);
          const fan = Math.exp(-(((cx + 25) / 14) ** 2) - ((cy - 5) / 10) ** 2);
          h += 120 * fan;
          break;
        }
        case 'mars-gale':
          mpp = 1200;
          h += crater(d, 58, 3500) + 4200 * Math.exp(-((d / 22) ** 2));
          break;
        case 'mars-arcadia-ice':
          mpp = 100;
          h *= 0.25;
          h -= 25 * Math.max(0, valueNoise(x / 6, y / 6, 11) - 0.6) * 10;
          break;
      }
      for (const [kx, ky, kr, kd] of craters) {
        const dd = Math.hypot(x - kx, y - ky);
        if (dd < kr * 3) h += crater(dd, kr, kr * 25 * kd);
      }
      field[y * W + x] = h;
    }
  let lo = Infinity;
  let hi = -Infinity;
  for (const v of field) {
    lo = Math.min(lo, v);
    hi = Math.max(hi, v);
  }
  const i16 = new Int16Array(W * H);
  for (let i = 0; i < field.length; i++) i16[i] = Math.round(((field[i] - lo) / (hi - lo)) * 65535 - 32768);
  return {
    width: W,
    height: H,
    metersPerPixel: mpp,
    minElevation: Math.round(lo),
    maxElevation: Math.round(hi),
    encoding: 'int16-base64',
    data: Buffer.from(i16.buffer).toString('base64'),
    provenance: { mock: true, processing: `${MOCK_NOTE} Procedural terrain, not a real DEM.` },
  };
}

// ---------- main ----------
function main() {
  mkdirSync(join(OUT, 'heightmaps'), { recursive: true });
  const provenance = (extra: object = {}) => ({
    mock: true,
    generatedAt: new Date().toISOString(),
    processing: MOCK_NOTE,
    datasets: [{ name: 'Natural Earth 110m land (land mask only)', url: 'https://www.naturalearthdata.com/', notes: 'Public domain' }],
    ...extra,
  });

  writeFileSync(join(OUT, 'features.json'), JSON.stringify({ version: 1, features: FEATURES, provenance: provenance() }, null, 2));
  writeFileSync(join(OUT, 'targets.json'), JSON.stringify({ targets: TARGETS, provenance: provenance() }, null, 2));

  const land = loadLand();
  const lat: number[] = [];
  const lon: number[] = [];
  const region: string[] = [];
  const values: Record<string, number[]> = Object.fromEntries(FEATURES.map((fd) => [fd.key, []]));
  for (let la = -90 + CELL_DEG / 2; la < 90; la += CELL_DEG)
    for (let lo = -180 + CELL_DEG / 2; lo < 180; lo += CELL_DEG) {
      if (!isLand(lo, la, land)) continue;
      lat.push(la);
      lon.push(lo);
      region.push(regionName(la, lo));
      const v = earthValues(la, lo);
      for (const fd of FEATURES) values[fd.key].push(v[fd.key]);
    }
  // A few cells have missing values so the "partial data" path is exercised.
  for (let i = 0; i < lat.length; i++) if (rand() < 0.03) values.rock_fraction[i] = null as unknown as number;
  writeFileSync(
    join(OUT, 'earth_cells.json'),
    JSON.stringify({ cellSizeDeg: CELL_DEG, count: lat.length, lat, lon, values, region, provenance: provenance() }),
  );

  const featured: FeaturedSite[] = SEEDS.map(({ overrides, tags: _tags, ...s }) => {
    const v = { ...earthValues(s.lat, s.lon), ...overrides };
    const norm = normalizeValues(v, FEATURES);
    const score: Record<string, number> = {};
    for (const tid of s.analogFor) {
      const t = TARGETS.find((x) => x.id === tid)!;
      const res = scoreVector(valuesGetter(norm), queryFromTarget(t, FEATURES));
      if (res) score[tid] = Math.round(res.score);
    }
    return { ...s, values: v, score, tour: s.tour && { ...s.tour, waypoints: waypointsFor(s.lat, s.lon) } };
  });
  writeFileSync(
    join(OUT, 'featured_analogs.json'),
    JSON.stringify(
      {
        featured,
        provenance: provenance({
          processing: `${MOCK_NOTE} Site names and coordinates are approximate seeds from the product guide; descriptions are draft text to verify before publishing.`,
        }),
      },
      null,
      2,
    ),
  );

  for (const t of TARGETS) writeFileSync(join(OUT, 'heightmaps', `${t.id}.json`), JSON.stringify(heightmap(t.id)));

  console.log(`features: ${FEATURES.length}, targets: ${TARGETS.length}, cells: ${lat.length}, featured: ${featured.length}`);
  console.table(featured.map((f) => ({ id: f.id, ...f.score })));
}

main();
