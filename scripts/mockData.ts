type Ring = number[][];
interface Poly {
  bbox: [number, number, number, number];
  rings: Ring[];
}
function loadLand(): Poly[] {
  const gj = JSON.parse(readFileSync(join(ROOT, 'scripts', 'vendor', 'ne_110m_land.geojson'), 'utf8'));
  const polys: Poly[] = [];
  for (const f of gj.features) {
    const g = f.geometry;
    const list: Ring[][] = g.type === 'Polygon' ? [g.coordinates] : g.coordinates;
    for (const rings of list) {
      let [x0, y0, x1, y1] = [Infinity, Infinity, -Infinity, -Infinity];
      for (const [x, y] of rings[0]) {
        x0 = Math.min(x0, x);
        y0 = Math.min(y0, y);
        x1 = Math.max(x1, x);
        y1 = Math.max(y1, y);
      }
      polys.push({ bbox: [x0, y0, x1, y1], rings });
    }
  }
  return polys;
}
function inRing(x: number, y: number, ring: Ring): boolean {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}
function isLand(lon: number, lat: number, polys: Poly[]): boolean {
  for (const p of polys) {
    const [x0, y0, x1, y1] = p.bbox;
    if (lon < x0 || lon > x1 || lat < y0 || lat > y1) continue;
    if (inRing(lon, lat, p.rings[0]) && !p.rings.slice(1).some((h) => inRing(lon, lat, h))) return true;
  }
  return false;
}

