type Vals = Record<string, number>;
function earthValues(lat: number, lon: number): Vals {
  const absLat = Math.abs(lat);
  const n1 = fbm(lat, lon, 1);
  const n2 = fbm(lat, lon, 7);
  const mountain = maxBlob(lat, lon, MOUNTAINS);
  const mFactor = clamp(mountain / 3000);
  const antarcticElev = lat < -70 ? 2000 + (-lat - 70) * 60 : lat < -64 ? 800 : 0;
  const elev = Math.max(-100, 150 + n1 * 400 + mountain + antarcticElev);

  let aridity = maxBlob(lat, lon, DESERTS);
  if (lat < -64) aridity = Math.max(aridity, 0.9);
  if (lat > 72) aridity = Math.max(aridity, 0.6);
  aridity = clamp(aridity + (n2 - 0.5) * 0.2);

  const wet = 1600 * Math.exp(-((lat / 12) ** 2)) + 700 * Math.exp(-(((absLat - 50) / 12) ** 2)) + 250;
  const precip = Math.max(1, wet * (1 - aridity) ** 2 * (0.7 + n1 * 0.6));

  const s2 = Math.sin((absLat * Math.PI) / 180) ** 2;
  const meanT = 300 - 50 * s2 ** 1.3 - 0.0065 * elev;
  const continental = 0.6 + 0.6 * aridity + 0.3 * n2;
  const seasonal = 2 + 24 * s2 * continental;
  const diurnal = 7 + 14 * aridity + elev * 0.0018 + n2 * 3;
  const tMin = meanT - seasonal - diurnal / 2 - 4;
  const tMax = meanT + seasonal + diurnal / 2 + aridity * 6;

  const ice = lat < -62 || (lat > 60 && lon > -74 && lon < -11) ? 0.95 : clamp(0.25 + (270 - meanT) / 35);
  const permafrost = meanT < 272 ? ice : clamp((272 - meanT) / 30, 0, 0.15);
  const warmth = clamp((meanT - 255) / 25);
  const ndvi = clamp((Math.log1p(precip) / Math.log1p(2200)) * warmth * (1 - aridity * 0.7) - (lat < -62 ? 1 : 0), 0, 0.88);
  const basalt = clamp(0.04 + maxBlob(lat, lon, VOLCANIC) + (n1 - 0.5) * 0.06);
  const glacial = lat < -62 || (lat > 60 && lon > -74 && lon < -11);
  const albedo = glacial ? 0.78 : clamp(0.12 + aridity * 0.24 - ndvi * 0.06 - basalt * 0.08 + n2 * 0.04, 0.05, 0.85);
  const slope = clamp(1.5 + mFactor * 18 + n1 * 4 + (glacial ? 1 : 0), 0, 40);
  const rough = Math.max(0.3, 1 + mFactor * 22 + n2 * 4);
  const rock = clamp(0.08 + aridity * 0.3 + mFactor * 0.3 - ndvi * 0.3 + (n1 - 0.5) * 0.1 - (glacial ? 0.1 : 0));
  const illum = clamp(0.5 - slope * 0.003 + (n2 - 0.5) * 0.02);
  const radiation = clamp(0.05 + 0.15 * (elev / 5000) + 0.1 * (absLat / 90));
  const pop = maxBlob(lat, lon, POPULATED);
  const isolation = clamp(0.92 - 0.8 * pop - (absLat < 60 ? 0.2 * (1 - aridity) : 0) + (n1 - 0.5) * 0.15 + (absLat > 66 ? 0.08 : 0));

  return {
    elevation_m: round(elev, 0),
    slope_deg: round(slope, 1),
    roughness_m: round(rough, 1),
    rock_fraction: round(rock, 2),
    temp_max_k: round(tMax, 0),
    temp_min_k: round(tMin, 0),
    temp_range_k: round(diurnal, 1),
    illum_fraction: round(illum, 2),
    ice_signal: round(permafrost, 2),
    basalt_fraction: round(basalt, 2),
    albedo: round(albedo, 2),
    vegetation_ndvi: round(ndvi, 2),
    precip_mm_yr: round(precip, 0),
    radiation_index: round(radiation, 2),
    isolation_index: round(isolation, 2),
  };
}

